package nthrc.mixin.minecraft;

import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraft.world.gen.structure.MapGenStructure;
import nthrc.Hook;
import nthrc.minecraft.StrongholdWorld;

/**
 * fixStrongholdLocateCrash: MapGenStronghold.getNearestStructurePos (func_180706_b) calls generatePositions, which reads world.getSeed(), without filling the
 * generator's world (MapGenBase only fills it in generate). Before the first chunk generated by this instance (Recurrent Complex wraps the generator), world is
 * null and the server crashes. Here it receives the lookup's world when still empty.
 *
 * SRG name and remap=false: the module's group has no refmap, and the harness and the game run with SRG names; the field access (world) is translated by the
 * jar's remap.
 */
@Mixin(targets = "net.minecraft.world.gen.structure.MapGenStronghold", remap = false)
public abstract class StrongholdWorldMixin extends MapGenStructure {

    @Inject(method = "func_180706_b", at = @At("HEAD"))
    private void nthrc$StrongholdWorldMixin$world(World worldIn, BlockPos pos, boolean findUnexplored, CallbackInfoReturnable<BlockPos> cir) {
        if (Hook.STRONGHOLD_WORLD.ok) {
            this.world = StrongholdWorld.fill(this.world, worldIn);
        }
    }

}
